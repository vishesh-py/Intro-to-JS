// Properties in javascript are the values associated with a JavaScript object. 
// A property can be known as information about the object.

// 1. String Properties:
const str = "Hello, World!";
console.log(str.length); // Output: 13

// 2. Array Properties:
const arr = [1, 2, 3, 4, 5];
console.log(arr.length); // Output: 5

// 3. Object Properties:
const obj = { name: "John", age: 30 };
console.log(obj.name); // Output: John
console.log(obj.age); // Output: 30


