// "+" operator does not work only for numbers, it also works for strings. When you use the "+" operator with strings,
//  and the process of adding one string to another string is called string concatenation. 
// It combines two or more strings into a single string.

// Example of string concatenation:

a = "Vishesh"
b = "Verma"

console.log(a + " " + b); // Output: Vishesh Verma  

