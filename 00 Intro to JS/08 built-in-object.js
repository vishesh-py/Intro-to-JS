// Built in Objects in JavaScript

// Math is a built-in JavaScript object.
// It provides mathematical methods and properties.

// Math.random() returns a random decimal number
// between 0 (inclusive) and 1 (exclusive).

console.log(Math.random());

// Output example:
// 0.2345

console.log(Math.random() * 50);
// Math.random() -> 0 to 1
// Multiply by 50 -> 0 to 50

// Math.floor() rounds a decimal number
// down to the nearest whole number.
console.log(Math.floor(7.9)); // 7
console.log(Math.floor(5.2)); // 5

